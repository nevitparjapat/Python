# WAP to Create a Grade System 

Marks=int(input("Enter a Student Marks : "))

if(Marks>=90):
    print(" A Grade")
elif(Marks>=75):
    print("B Grade")
elif(Marks>=55):
    print("C Grade")
elif(Marks>=45):
    print("D Grade")
elif(Marks>=33):
    print("E Grade")

else:
    print("YOU ARE FAIL")
 
 